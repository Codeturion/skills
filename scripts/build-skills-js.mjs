// Generates site/skills.js from skills/*/site.json + site/roadmap.json.
// Run from the repo root: node scripts/build-skills-js.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";

const REPO = "https://github.com/Codeturion/skills";
const required = ["id", "slug", "area", "status", "verified", "blurb", "detail", "sections", "requires", "notes"];

const entries = [];
for (const dir of readdirSync("skills", { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const p = `skills/${dir.name}/site.json`;
  if (!existsSync(p)) {
    console.warn(`warn: ${dir.name} has no site.json, skipped`);
    continue;
  }
  const e = JSON.parse(readFileSync(p, "utf8"));
  for (const k of required) if (!(k in e)) throw new Error(`${p}: missing "${k}"`);
  if (e.slug !== dir.name) throw new Error(`${p}: slug "${e.slug}" does not match folder "${dir.name}"`);
  e.repo = `${REPO}/tree/main/skills/${e.slug}`;
  entries.push(e);
}

for (const e of JSON.parse(readFileSync("site/roadmap.json", "utf8"))) {
  for (const k of required) if (!(k in e)) throw new Error(`roadmap.json ${e.id ?? "?"}: missing "${k}"`);
  e.repo = REPO;
  entries.push(e);
}

const ids = new Set();
for (const e of entries) {
  if (ids.has(e.id)) throw new Error(`duplicate id "${e.id}"`);
  ids.add(e.id);
  e.name = e.slug;
}

const areas = ["all", ...new Set(entries.map(e => e.area))];
const statuses = ["all", ...new Set(entries.map(e => e.status))];

const out =
  "// GENERATED by scripts/build-skills-js.mjs. Do not edit by hand.\n" +
  "// Skill cards live in skills/<name>/site.json; planned rows in site/roadmap.json.\n" +
  "const SKILLS = " + JSON.stringify(entries, null, 2) + ";\n\n" +
  "const AREAS = " + JSON.stringify(areas) + ";\n" +
  "const STATUSES = " + JSON.stringify(statuses) + ";\n" +
  "const RANK = { verified: 0, draft: 1, planned: 2 };\n";

writeFileSync("site/skills.js", out);
console.log(`site/skills.js: ${entries.length} entries (${entries.filter(e => e.status === "verified").length} verified)`);
